import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {reverseAuthorLayer} from './scene-data-runtime.mjs';
const sha=v=>createHash('sha256').update(v).digest('hex'),root=new URL('../',import.meta.url);
const release=JSON.parse(await readFile(new URL('tests/scene-release-layer.json',root)));
const startup=JSON.parse(await readFile(new URL('tests/scene-startup-layer.json',root)));
const reservations=JSON.parse(await readFile(new URL('tests/scene-reservation-layer.json',root)));
const extension=JSON.parse(await readFile(new URL('tests/scene-parameter-layer.json',root)));
const current=await readFile(new URL('index.html',root),'utf8'),layer=JSON.parse(await readFile(new URL('tests/scene-data-layer.json',root))),binding=JSON.parse(await readFile(new URL('tests/scene-data-main-binding.json',root)));
const released=reverseAuthorLayer(current,release),sw=await readFile(new URL('frame-sw.js',root),'utf8');
assert.equal(sha(released),release.baseSHA256,'Release reverses exactly to native-tested R2');
assert.equal(release.serviceWorker.baseSHA256,binding.unchangedFiles['frame-sw.js']);
assert.ok(current.includes('<meta name="frame-version" content="'+release.releaseVersion+'">'));
assert.ok(current.includes('<title>Frame '+release.releaseVersion+'</title>'));
assert.ok(sw.includes("const VERSION='"+release.releaseVersion+"',CACHE="));
const prior=reverseAuthorLayer(released,startup);
assert.equal(sha(prior),startup.baseSHA256);
assert.equal(sha(reverseAuthorLayer(reverseAuthorLayer(prior,reservations),extension)),extension.baseSHA256);
assert.equal(sha(reverseAuthorLayer(prior,reservations)),reservations.baseSHA256);
assert.equal(layer.baseCommit,binding.baseCommit);
assert.equal(layer.baseSHA256,binding.baseIndexSHA256);
assert.equal(sha(reverseAuthorLayer(reverseAuthorLayer(reverseAuthorLayer(prior,reservations),extension),layer)),binding.baseIndexSHA256,'Complete main index is byte-identical after exact reversal');
for(const [file,hash]of Object.entries(binding.unchangedFiles))assert.equal(sha(file==='frame-sw.js'?reverseAuthorLayer(sw,release.serviceWorker):await readFile(new URL(file,root))),hash,file);
console.log(JSON.stringify({pass:true,checks:16,baseCommit:binding.baseCommit,indexSHA256:sha(current),baseSHA256:binding.baseIndexSHA256,scope:'Five exact reversal layers to original main; unchanged Docs; exact version-only service-worker reversal'}));
